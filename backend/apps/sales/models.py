import uuid

from django.conf import settings
from django.db import models

from apps.core.models import TimeStampedModel


class Sale(TimeStampedModel):
    class Method(models.TextChoices):
        CASH = "cash", "Cash"
        MOBILE_MONEY = "mobile_money", "Mobile money (Zamtel Kwacha)"

    class Status(models.TextChoices):
        RECORDED = "recorded", "Recorded"
        VOIDED = "voided", "Voided"

    class Match(models.TextChoices):
        NOT_APPLICABLE = "n/a", "Cash - checked at daily close"
        PENDING = "pending", "Waiting for payment"
        MATCHED = "matched", "Matched to payment"
        NEEDS_REVIEW = "review", "Needs review"

    shop = models.ForeignKey("shops.Shop", on_delete=models.CASCADE, related_name="sales")
    # Generated by the phone so a retried/offline sale is never recorded twice.
    client_id = models.UUIDField(default=uuid.uuid4)
    recorded_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, on_delete=models.SET_NULL, related_name="recorded_sales"
    )
    payment_method = models.CharField(max_length=12, choices=Method.choices)
    provider = models.CharField(max_length=8, blank=True)
    total = models.DecimalField(max_digits=12, decimal_places=2)
    status = models.CharField(max_length=8, choices=Status.choices, default=Status.RECORDED)
    match_status = models.CharField(max_length=8, choices=Match.choices, default=Match.NOT_APPLICABLE)
    sold_at = models.DateTimeField()
    sale_date = models.DateField(db_index=True)
    payer_phone = models.CharField(max_length=15, blank=True)
    payment_reference = models.CharField(max_length=60, blank=True)
    note = models.CharField(max_length=255, blank=True)
    voided_at = models.DateTimeField(null=True, blank=True)
    voided_by = models.ForeignKey(
        settings.AUTH_USER_MODEL, null=True, blank=True, on_delete=models.SET_NULL, related_name="+"
    )
    void_reason = models.CharField(max_length=255, blank=True)

    class Meta:
        ordering = ["-sold_at", "-id"]
        constraints = [models.UniqueConstraint(fields=["shop", "client_id"], name="uniq_sale_client_id")]
        indexes = [models.Index(fields=["shop", "sale_date"])]

    def __str__(self):
        return f"Sale #{self.pk} K{self.total}"


class SaleLine(models.Model):
    sale = models.ForeignKey(Sale, on_delete=models.CASCADE, related_name="lines")
    item = models.ForeignKey("inventory.Item", null=True, blank=True, on_delete=models.RESTRICT, related_name="+")
    description = models.CharField(max_length=150, blank=True)
    quantity = models.PositiveIntegerField(default=1)
    unit_price = models.DecimalField(max_digits=10, decimal_places=2)
    line_total = models.DecimalField(max_digits=12, decimal_places=2)


class MobilePayment(TimeStampedModel):
    """Money received on the shop's Zamtel Kwacha merchant number (simulated in the prototype)."""

    class Provider(models.TextChoices):
        MTN = "MTN", "MTN"
        AIRTEL = "Airtel", "Airtel"
        ZAMTEL = "Zamtel", "Zamtel"

    class Status(models.TextChoices):
        UNMATCHED = "unmatched", "Not matched to a sale"
        MATCHED = "matched", "Matched"
        NEEDS_REVIEW = "review", "Needs review"
        IGNORED = "ignored", "Ignored by the owner"

    class Source(models.TextChoices):
        SIMULATED = "simulated", "Simulated"
        WEBHOOK = "webhook", "Zamtel webhook"

    shop = models.ForeignKey("shops.Shop", on_delete=models.CASCADE, related_name="mobile_payments")
    provider_ref = models.CharField(max_length=60)
    provider = models.CharField(max_length=8, blank=True)
    payer_phone = models.CharField(max_length=15, blank=True)
    amount = models.DecimalField(max_digits=12, decimal_places=2)
    received_at = models.DateTimeField()
    status = models.CharField(max_length=10, choices=Status.choices, default=Status.UNMATCHED)
    sale = models.OneToOneField(Sale, null=True, blank=True, on_delete=models.SET_NULL, related_name="payment")
    source = models.CharField(max_length=10, choices=Source.choices, default=Source.SIMULATED)

    class Meta:
        ordering = ["-received_at"]
        constraints = [
            models.UniqueConstraint(
                fields=["shop", "provider_ref"],
                condition=~models.Q(provider_ref=""),
                name="uniq_payment_ref",
            )
        ]
