from django.contrib.auth.models import (
    AbstractBaseUser,
    BaseUserManager,
    PermissionsMixin,
)
from django.db import models
from django.db.models import Q

from apps.core.utils import validate_zm_phone


class UserManager(BaseUserManager):
    use_in_migrations = True

    def _create(self, phone, password, **extra):
        if not phone:
            raise ValueError("A phone number is required.")
        phone = validate_zm_phone(phone)
        user = self.model(phone=phone, **extra)
        user.set_password(password)
        user.save(using=self._db)
        return user

    def create_user(self, phone, password=None, **extra):
        extra.setdefault("is_staff", False)
        extra.setdefault("is_superuser", False)
        return self._create(phone, password, **extra)

    def create_superuser(self, phone, password=None, **extra):
        extra.setdefault("is_staff", True)
        extra.setdefault("is_superuser", True)
        return self._create(phone, password, **extra)


class User(AbstractBaseUser, PermissionsMixin):
    """Phone number is the login. Owners and assistants are both Users; their role per shop
    lives on shops.Membership.

    Email is the online identity used by the mobile app. Password sign-in stays blocked
    until a magic link proves the owner controls the inbox. The phone PIN never reaches
    this model: it is an offline unlock checked on the phone.
    """

    class Language(models.TextChoices):
        ENGLISH = "en", "English"
        NYANJA = "ny", "Nyanja"

    phone = models.CharField(max_length=15, unique=True)
    full_name = models.CharField(max_length=150, blank=True)
    email = models.EmailField(blank=True)
    email_verified_at = models.DateTimeField(null=True, blank=True)
    # The id generated by the phone before the first registration request, kept
    # so a lost response can be retried without creating a second account.
    client_id = models.CharField(max_length=64, unique=True, null=True, blank=True)
    language = models.CharField(max_length=2, choices=Language.choices, default=Language.ENGLISH)
    is_active = models.BooleanField(default=True)
    is_staff = models.BooleanField(default=False)
    date_joined = models.DateTimeField(auto_now_add=True)

    objects = UserManager()
    USERNAME_FIELD = "phone"
    REQUIRED_FIELDS = []

    class Meta:
        constraints = [
            models.UniqueConstraint(
                fields=["email"], condition=~Q(email=""), name="uniq_user_email"
            )
        ]

    def __str__(self):
        return f"{self.full_name or 'User'} ({self.phone})"


class StaffProfile(models.Model):
    """The extra credentials an assistant needs for the first sign-in.

    The phone keeps its own salted PIN hash for offline sign-in. This row keeps a
    Django password verifier, which a database leak cannot turn into a working
    offline hash, plus the lockout counter.
    """

    user = models.OneToOneField(
        "accounts.User", on_delete=models.CASCADE, related_name="staff_profile"
    )
    client_id = models.CharField(max_length=64, unique=True, null=True, blank=True)
    pin_verifier = models.CharField(max_length=255, blank=True, default="")
    first_signed_in_at = models.DateTimeField(null=True, blank=True)
    failed_sign_ins = models.PositiveSmallIntegerField(default=0)
    locked_until = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return f"Staff credentials for {self.user}"


class MagicLinkToken(models.Model):
    """A single-use, short-lived link sent to the user's email.

    Only the SHA-256 hash is stored. Requesting a new link marks the previous
    one used, so there is never more than one live link per user.
    """

    user = models.ForeignKey("accounts.User", on_delete=models.CASCADE, related_name="magic_links")
    token_hash = models.CharField(max_length=64, unique=True)
    expires_at = models.DateTimeField()
    used_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]


class PinResetCode(models.Model):
    """A short-lived code for resetting a forgotten phone PIN.

    Only the hash is stored. Requesting a new code marks the previous one used,
    so there is never more than one live code for a user.
    """

    user = models.ForeignKey("accounts.User", on_delete=models.CASCADE, related_name="reset_codes")
    code_hash = models.CharField(max_length=255)
    expires_at = models.DateTimeField()
    attempts = models.PositiveSmallIntegerField(default=0)
    used_at = models.DateTimeField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]
