#requires -Version 5.1
[CmdletBinding()]
param(
    [switch]$SkipBackend,
    [switch]$SkipMobile
)

$ErrorActionPreference = 'Stop'
$RepoRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$BackendDir = Join-Path $RepoRoot 'backend'
$MobileDir = Join-Path $RepoRoot 'mobile'
$VenvDir = Join-Path $BackendDir '.venv'

if ($env:OS -eq 'Windows_NT') {
    $VenvPython = Join-Path $VenvDir 'Scripts\python.exe'
} else {
    $VenvPython = Join-Path $VenvDir 'bin/python'
}

function Write-Step {
    param([string]$Message)
    Write-Host ''
    Write-Host "==> $Message" -ForegroundColor Cyan
}

function Find-Python {
    foreach ($candidate in @('python', 'py')) {
        $command = Get-Command $candidate -ErrorAction SilentlyContinue
        if (-not $command) { continue }
        $version = & $command.Source -c "import sys; print('.'.join(map(str, sys.version_info[:3])))" 2>$null
        if ($LASTEXITCODE -eq 0 -and $version) {
            return @{ Path = $command.Source; Version = [version]($version.Trim()) }
        }
    }
    throw 'Python 3.10 or newer is required. Install it and make sure "python" or "py" is on PATH.'
}

function Find-Node {
    $command = Get-Command node -ErrorAction SilentlyContinue
    if (-not $command) {
        throw 'Node.js is required. Install Node 26 LTS (see mobile/.nvmrc).'
    }
    $raw = (& $command.Source --version).Trim()
    return [version]($raw.TrimStart('v'))
}

if (-not $SkipBackend) {
    Write-Step 'Checking Python'
    $python = Find-Python
    if ($python.Version -lt [version]'3.10') {
        throw "Python $($python.Version) is too old. Django 5.2 needs Python 3.10 or newer."
    }
    Write-Host "Python $($python.Version) found."

    if (-not (Test-Path $VenvPython)) {
        Write-Step 'Creating backend/.venv'
        & $python.Path -m venv $VenvDir
        if ($LASTEXITCODE -ne 0) { throw 'Could not create backend/.venv.' }
    } else {
        Write-Host 'backend/.venv already exists.'
    }

    Write-Step 'Installing backend dependencies'
    & $VenvPython -m pip install --upgrade pip
    if ($LASTEXITCODE -ne 0) { throw 'Could not upgrade pip.' }
    & $VenvPython -m pip install -r (Join-Path $BackendDir 'requirements.txt')
    if ($LASTEXITCODE -ne 0) { throw 'Could not install backend requirements.' }

    $envFile = Join-Path $BackendDir '.env'
    if (-not (Test-Path $envFile)) {
        Write-Step 'Creating backend/.env for local development'
        $secret = (& $VenvPython -c "import secrets; print(secrets.token_urlsafe(50))").Trim()
        if ($LASTEXITCODE -ne 0 -or -not $secret) { throw 'Could not generate a development secret key.' }
        $content = @"
# Generated by scripts/setup.ps1 for local development.
# Local-demo profile: one-time tokens are shown in API responses. Never use
# this file on a deployed server. See backend/.env.example for SMTP, Postgres
# and safe production defaults.
DJANGO_DEBUG=1
DJANGO_SECRET_KEY=$secret
DJANGO_ALLOWED_HOSTS=*
EXPOSE_EMAIL_TOKEN=1
EXPOSE_RESET_CODE=1
"@
        $utf8NoBom = [System.Text.UTF8Encoding]::new($false)
        [System.IO.File]::WriteAllText($envFile, $content, $utf8NoBom)
        Write-Host 'Created backend/.env with local-demo settings.' -ForegroundColor Yellow
        Write-Host 'Magic links and PIN reset codes will be printed by the backend / returned to the app.' -ForegroundColor Yellow
    } else {
        Write-Host 'backend/.env already exists; leaving it untouched.'
    }

    Write-Step 'Checking Django settings'
    Push-Location $BackendDir
    try {
        & $VenvPython manage.py check
        if ($LASTEXITCODE -ne 0) {
            throw 'backend/.env is not usable. Set DJANGO_SECRET_KEY and DJANGO_ALLOWED_HOSTS, or delete backend/.env and rerun this script to create local-demo values.'
        }

        Write-Step 'Applying database migrations'
        & $VenvPython manage.py migrate --noinput
        if ($LASTEXITCODE -ne 0) { throw 'Database migration failed.' }
    } finally {
        Pop-Location
    }
}

if (-not $SkipMobile) {
    Write-Step 'Checking Node'
    $nodeVersion = Find-Node
    $supportedNode = (
        ($nodeVersion.Major -eq 22 -and $nodeVersion -ge [version]'22.13.0') -or
        ($nodeVersion.Major -eq 24 -and $nodeVersion -ge [version]'24.3.0') -or
        $nodeVersion.Major -ge 26
    )
    if (-not $supportedNode) {
        Write-Warning "Node $nodeVersion may not work with Expo 58. Use Node 26 LTS (mobile/.nvmrc)."
    } else {
        Write-Host "Node $nodeVersion found."
    }

    if (-not (Get-Command npm -ErrorAction SilentlyContinue)) {
        throw 'npm is required. Install Node 26 LTS (see mobile/.nvmrc).'
    }

    $packageLock = Join-Path $MobileDir 'package-lock.json'
    $installMarker = Join-Path $MobileDir 'node_modules\.package-lock.json'
    $needsInstall = -not (Test-Path $installMarker)
    if (-not $needsInstall -and (Test-Path $packageLock)) {
        $needsInstall = (Get-Item $packageLock).LastWriteTimeUtc -gt (Get-Item $installMarker).LastWriteTimeUtc
    }

    if ($needsInstall) {
        Write-Step 'Installing mobile dependencies'
        Push-Location $MobileDir
        try {
            & npm install
            if ($LASTEXITCODE -ne 0) { throw 'npm install failed.' }
        } finally {
            Pop-Location
        }
    } else {
        Write-Host 'Mobile dependencies already installed.'
    }
}

Write-Host ''
Write-Host 'Setup complete.' -ForegroundColor Green
Write-Host '  Start both:      .\scripts\start.ps1'
Write-Host '  Backend only:    .\scripts\start-backend.ps1'
Write-Host '  Mobile only:     .\scripts\start-mobile.ps1'
Write-Host '  Run checks:      .\scripts\test.ps1'
Write-Host ''
Write-Host 'If PowerShell blocks the scripts, use:'
Write-Host '  powershell -ExecutionPolicy Bypass -File .\scripts\setup.ps1'
